#!/usr/bin/env bash
# ==============================================================
# 按 GE-Proton（gloriouseggroll/proton-ge-custom）的 patch 流程准备 Wine 源码树
# ==============================================================
# 目标：复刻 GE 的 wine 源码准备过程，不改动调用方的 configure/make/打包流程。
#
# GE 的 wine 不是某个现成仓库分支，而是三步拼出来的：
#   1. ValveSoftware/wine @ <GE .gitmodules 里 pin 的 sha>
#   2. wine-staging     @ <GE .gitmodules 里 pin 的 sha>，用 patchinstall.py 打
#      大部分补丁，外加 GE 自己维护的 11 组 rebase 版补丁
#   3. GE 仓库 patches/wine-hotfixes/ 下 GE 自己的额外补丁
#
# 关键陷阱（已实测确认）：
#   Valve 在 commit e813ca57 里删除了 configure 与 include/config.h.in
#   （"Those are autogenerated by Proton's build system and get outdated
#    very quickly."），所以 pin 出来的树**根本没有 configure**，
#   直接 ../configure 会报 No such file or directory。
#
#   GE 的做法是 `git revert --no-commit e813ca57` 把这两个文件放回来，
#   但它自己的注释写得很清楚：
#     "Bring back configure files. Staging uses them to regenerate
#      fresh ones"
#   也就是说这两个文件只是**占位**，真正的 configure 由 GE Makefile 的
#   rules-autoconf（autoreconf）重新生成。
#
#   本 workflow 是直接调用 ../configure，不走 GE 的 Makefile，所以
#   必须自己生成：占位 -> 打完所有补丁 -> ./autogen.sh 生成与补丁后
#   源码一致的 configure / include/config.h.in。
#   另外 e813ca57 的父提交（82fa1cf3）是 2022-12 的产物，而 pin 是
#   2026-10 的树，直接下载那份旧 configure 会缺 4 年的检查项，因此
#   只在 autogen 失败时作为最后兜底。
#
# X11 说明：本脚本默认跳过全部 Wayland 相关补丁（GE 的
#   patches/wine-hotfixes/wine-wayland/、em-fixups/、
#   wineland-child-rendering/ 三组）。设备侧用 X11，
#   winewayland.drv 不会被编译/使用，跳过可省 ~170 个补丁的失败风险。
#   需要 Wayland 时传 GE_ENABLE_WAYLAND=1。
# ==============================================================

set -euo pipefail

WINE_PIN="${GE_WINE_PIN:-c53678ab22a85f0fad3588dd34f0452a463bd015}"
STAGING_PIN="${GE_STAGING_PIN:-6cc805ea57132eeaf44764e9213823c9b8d0d300}"
GE_REPO="${GE_REPO:-gloriouseggroll/proton-ge-custom}"
GE_ENABLE_WAYLAND="${GE_ENABLE_WAYLAND:-0}"

# e813ca57 就是 Valve 删掉 configure / config.h.in 的那个提交。
# 恢复内容 = 该提交父版本。
CONFIGURE_DELETED_BY="e813ca5771658b00875924ab88d525322e50d39f"

WINE_URL="https://github.com/ValveSoftware/wine"
STAGING_URL="https://github.com/wine-staging/wine-staging"

log() { echo "[ge-wine] $*"; }
die() { echo "[ge-wine][FATAL] $*" >&2; exit 1; }

BUILD_DIR="${BUILD_DIR:-/tmp/build_wine_ge}"
echo "=============================================="
echo " GE-Proton 方式准备 Wine 源码"
echo "=============================================="
echo "  Wine    pin : $WINE_PIN"
echo "  Staging pin : $STAGING_PIN"
echo "  GE 仓库     : $GE_REPO"
echo "  Wayland     : $GE_ENABLE_WAYLAND"
echo "  工作目录    : $BUILD_DIR"
echo "=============================================="

mkdir -p "$BUILD_DIR"
cd "$BUILD_DIR"

# --------------------------------------------------------------
# 1) ValveSoftware/wine @ pin
# --------------------------------------------------------------
log "克隆 ValveSoftware/wine @ ${WINE_PIN:0:12}"
rm -rf wine
git init -q wine
cd wine
git remote add origin "$WINE_URL"
# 按 sha 浅拉：--depth 1 直接取该提交，省掉 200MB+ 历史
if ! git fetch -q --depth 1 origin "$WINE_PIN"; then
  die "拉取 ValveSoftware/wine $WINE_PIN 失败"
fi
git checkout -q FETCH_HEAD
[ -f VERSION ] || die "Wine 源码树不完整（缺 VERSION）"
log "VERSION: $(cat VERSION)"

# --------------------------------------------------------------
# 2) 恢复被 Valve 删除的 configure / include/config.h.in
# --------------------------------------------------------------
# 具体生成放到第 7.5 节（必须等所有补丁打完，configure 才与源码一致）。
# 这里只放占位，避免 wine-staging 的 patchinstall.py 找不到文件。
if [ -f configure ] && [ -s configure ]; then
  log "configure 已存在于 pin 树中（异常，按理已被 Valve 删除）"
else
  log "configure 缺失（Valve 在 e813ca57 里删了）→ 先占位，第 7.5 节统一生成"
  printf '#!/bin/sh\necho "ge-wine: configure placeholder, will be regenerated by autogen.sh" >&2\nexit 1\n' > configure
  chmod +x configure
fi
if [ ! -f include/config.h.in ]; then
  mkdir -p include
  : > include/config.h.in
fi

# --------------------------------------------------------------
# 3) wine-staging @ pin（放到 wine 的兄弟目录，GE 脚本用 ../wine-staging）
# --------------------------------------------------------------
log "克隆 wine-staging @ ${STAGING_PIN:0:12}"
cd "$BUILD_DIR"
rm -rf wine-staging
git init -q wine-staging
cd wine-staging
git remote add origin "$STAGING_URL"
if ! git fetch -q --depth 1 origin "$STAGING_PIN"; then
  die "拉取 wine-staging $STAGING_PIN 失败"
fi
git checkout -q FETCH_HEAD
[ -f staging/patchinstall.py ] || die "wine-staging 缺 staging/patchinstall.py"
log "wine-staging 就绪（patches: $(ls patches 2>/dev/null | wc -l) 组）"

# --------------------------------------------------------------
# 4) 打 staging 补丁（完全照搬 GE 的禁用列表）
# --------------------------------------------------------------
cd "$BUILD_DIR/wine"
log "应用 wine-staging 补丁（照搬 GE 的 -W 禁用列表）"
# 说明：staging 上游自带一大批补丁；GE 关掉其中 31 项，
# 原因是「与 Proton 自带实现冲突 / 破坏游戏 / 已由 Wine 上游合并」。
# 这些开关不能省，否则会和 ValveSoftware/wine 的 Proton 改动打架。
python3 ../wine-staging/staging/patchinstall.py DESTDIR="." --all --no-autoconf \
  -W server-Signal_Thread \
  -W server-Stored_ACLs \
  -W server-File_Permissions \
  -W kernel32-CopyFileEx \
  -W dbghelp-Debug_Symbols \
  -W version-VerQueryValue \
  -W mf_http_support \
  -W ntdll-Serial_Port_Detection \
  -W server-PeekMessage \
  -W msxml3-FreeThreadedXMLHTTP60 \
  -W ntdll-ForceBottomUpAlloc \
  -W ntdll-NtDevicePath \
  -W user32-rawinput-mouse \
  -W user32-recursive-activation \
  -W d3dx9_36-D3DXStubs \
  -W wined3d-zero-inf-shaders \
  -W ntdll-RtlQueryPackageIdentity \
  -W vkd3d-latest \
  -W loader-KeyboardLayouts \
  -W ntdll-Syscall_Emulation \
  -W ntdll_reg_flush \
  -W ntdll-Hide_Wine_Exports \
  -W kernel32-Debugger \
  -W ntdll-ext4-case-folder \
  -W winex11-Window_Style \
  -W wininet-Cleanup \
  -W wintrust-WTHelperGetProvCertFromChain \
  -W winex11-ime-check-thread-data \
  -W winex11-Fixed-scancodes \
  -W winedevice-Default_Drivers \
  -W Staging
log "staging 批量补丁完成"

# --------------------------------------------------------------
# 5) 稀疏拉取 GE 的补丁集
# --------------------------------------------------------------
cd "$BUILD_DIR"
rm -rf ge-src
log "稀疏克隆 GE 补丁集（只取 patches/）"
if ! git clone -q --depth 1 --filter=blob:none --sparse \
      "https://github.com/${GE_REPO}.git" ge-src; then
  die "克隆 GE 仓库失败"
fi
cd ge-src
git sparse-checkout set patches >/dev/null 2>&1 || die "sparse-checkout 失败"
[ -d patches/wine-hotfixes ] || die "GE 补丁集不完整（缺 patches/wine-hotfixes）"
log "GE 补丁集就绪"

# --------------------------------------------------------------
# 6) GE 手动应用的那 11 组 rebase 版补丁
#    （对应 GE 脚本里 "applied manually" 的注释）
# --------------------------------------------------------------
cd "$BUILD_DIR/wine"
GF="$BUILD_DIR/ge-src/patches"

apply_dir() {
  local d="$1"
  local label="$2"
  if [ ! -d "$d" ]; then
    log "  跳过 $label（目录不存在）"
    return 0
  fi
  local n=0 bad=0
  for p in "$d"/*.patch; do
    [ -f "$p" ] || continue
    n=$((n + 1))
    if ! patch -Np1 --batch --forward --no-backup-if-mismatch <"$p" >/dev/null 2>&1; then
      bad=$((bad + 1))
      log "    WARN: $(basename "$p") 打不上（继续）"
    fi
  done
  log "  $label: $n 份，失败 $bad"
}

log "应用 GE 手动 rebase 补丁组"
apply_dir "$GF/wine-hotfixes/wine-staging/winedevice-Default_Drivers" "winedevice-Default_Drivers"
apply_dir "$GF/wine-hotfixes/wine-staging/ntdll-Hide_Wine_Exports" "ntdll-Hide_Wine_Exports"
apply_dir "$GF/wine-hotfixes/wine-staging/kernel32-Debugger" "kernel32-Debugger"
apply_dir "$GF/wine-hotfixes/wine-staging/ntdll-ext4-case-folder" "ntdll-ext4-case-folder"
apply_dir "$GF/wine-hotfixes/wine-staging/winex11-Window_Style" "winex11-Window_Style"
# 这两个来自 staging 树本身，不是 GE hotfixes
apply_dir "$BUILD_DIR/wine-staging/patches/wininet-Cleanup" "wininet-Cleanup"
apply_dir "$BUILD_DIR/wine-staging/patches/Staging" "Staging"
apply_dir "$GF/wine-hotfixes/wine-staging/winex11-ime-check-thread-data" "winex11-ime-check-thread-data"
apply_dir "$GF/wine-hotfixes/wine-staging/winex11-Fixed-scancodes" "winex11-Fixed-scancodes"
# GE 注释里写着这三组是 "cleanup -Werror"，即为了过 -Werror 的清理补丁
apply_dir "$GF/wine-hotfixes/wine-staging/comctl32_animate_avi" "comctl32_animate_avi"
apply_dir "$GF/wine-hotfixes/wine-staging/d3drm-starwars" "d3drm-starwars"
apply_dir "$GF/wine-hotfixes/wine-staging/windowscodecs-TIFF_Support" "windowscodecs-TIFF_Support"
apply_dir "$GF/wine-hotfixes/wine-staging/mmsystem.dll16-MIDIHDR_Refcount" "mmsystem.dll16-MIDIHDR_Refcount"

# --------------------------------------------------------------
# 7) 可选：Wayland 补丁组（默认关闭，设备侧走 X11）
# --------------------------------------------------------------
if [ "$GE_ENABLE_WAYLAND" = "1" ]; then
  log "应用 Wayland 补丁组（GE_ENABLE_WAYLAND=1）"
  apply_dir "$GF/wine-hotfixes/wine-wayland" "wine-wayland"
  apply_dir "$GF/wine-hotfixes/wineland-child-rendering" "wineland-child-rendering"
  if [ -d "$GF/wine-hotfixes/em-fixups" ]; then
    for p in "$GF"/wine-hotfixes/em-fixups/*.patch; do
      [ -f "$p" ] || continue
      case "$p" in
        */0001-winewayland-add-SNI-tray-icons-and-native-context-me.patch)
          log "    跳过 0001（GE 也跳过，由下面单独处理）"
          ;;
        *)
          patch -Np1 --batch --forward --no-backup-if-mismatch <"$p" >/dev/null 2>&1 \
            || log "    WARN: $(basename "$p") 打不上"
          ;;
      esac
    done
  fi
else
  log "跳过 Wayland 补丁组（走 X11，winewayland.drv 不用编译）"
fi

# --------------------------------------------------------------
# 7.5) 生成 configure / include/config.h.in
#      必须在所有补丁打完以后做：这样生成的 configure 才和
#      patch 过的 configure.ac / Makefile.in 一致。
#      优先级：./autogen.sh（上游 Wine 官方方式，等同 GE 的 rules-autoconf）
#              → autoconf + autoheader
#              → 下载 e813ca57 父版本（2022 老文件，仅兜底）
# --------------------------------------------------------------
cd "$BUILD_DIR/wine"
log "生成 configure（configure.ac $(wc -l < configure.ac) 行）"

_configure_ok=0

if [ -f autogen.sh ]; then
  log "  尝试 ./autogen.sh"
  chmod +x autogen.sh 2>/dev/null || true
  chmod +x tools/make_requests tools/make_specfiles 2>/dev/null || true
  if ./autogen.sh > /tmp/ge_autogen.log 2>&1; then
    _configure_ok=1
    log "  autogen.sh 成功"
  else
    log "  WARN: autogen.sh 失败，日志尾部："
    tail -n 15 /tmp/ge_autogen.log 2>/dev/null | sed 's/^/        /' || true
  fi
fi

if [ "$_configure_ok" = "0" ]; then
  log "  尝试 autoconf + autoheader"
  if autoconf -o configure configure.ac > /tmp/ge_autoconf.log 2>&1 && \
     autoheader -o include/config.h.in configure.ac >> /tmp/ge_autoconf.log 2>&1; then
    _configure_ok=1
    log "  autoconf/autoheader 成功"
  else
    log "  WARN: autoconf 失败，日志尾部："
    tail -n 15 /tmp/ge_autoconf.log 2>/dev/null | sed 's/^/        /' || true
  fi
fi

if [ "$_configure_ok" = "0" ]; then
  log "  WARN: 退回到 e813ca57 父版本的 configure（2022 老文件，可能与 2026 源码不匹配）"
  _parent="$(
    curl -sL -m 60 \
      -H "Accept: application/vnd.github+json" \
      ${GHT:+-H "Authorization: token $GHT"} \
      "https://api.github.com/repos/ValveSoftware/wine/commits/${CONFIGURE_DELETED_BY}" \
    | python3 -c "import sys,json;d=json.load(sys.stdin);ps=d.get('parents') or [];print(ps[0]['sha'] if ps else '')"
  )"
  if [ -n "$_parent" ]; then
    for f in configure include/config.h.in; do
      mkdir -p "$(dirname "$f")"
      curl -sL -m 180 -f \
        ${GHT:+-H "Authorization: token $GHT"} \
        "https://raw.githubusercontent.com/ValveSoftware/wine/${_parent}/${f}" \
        -o "$f" && [ -s "$f" ] && log "  兜底恢复 $f"
    done
  fi
fi

chmod +x configure 2>/dev/null || true
[ -s configure ] || die "configure 最终仍为空"
[ -s include/config.h.in ] || die "include/config.h.in 最终仍为空"
# 关键校验：必须是能跑的真 configure，不能是占位脚本
if head -n 3 configure | grep -q 'ge-wine: configure placeholder'; then
  die "configure 仍是占位脚本（autogen 与兜底全部失败）"
fi
log "  configure $(wc -l < configure) 行 / config.h.in $(wc -l < include/config.h.in) 行"

# 清掉任何残留 .rej/.orig，避免后续步骤误判
find . -name '*.rej' -delete 2>/dev/null || true
find . -name '*.orig' -delete 2>/dev/null || true

# --------------------------------------------------------------
# 8) 结果自检
# --------------------------------------------------------------
log "自检"
[ -s configure ] || die "最终仍缺 configure"
[ -x configure ] || die "configure 不可执行"
[ -s include/config.h.in ] || die "最终仍缺 include/config.h.in"
# configure 必须真的带有 pin 树的版本信息，而不是空壳
grep -q 'WINE_VERSION\|Copyright' configure || die "configure 内容异常"
[ -d dlls/winedmo ] || die "缺 dlls/winedmo（Wine 树不完整）"
[ -d server ] || die "缺 server/（Wine 树不完整）"
# 确认 staging 确实打进去了：Staging 组的标志性文件
if [ -f "$BUILD_DIR/wine-staging/patches/Staging"/*.patch ] 2>/dev/null; then
  log "  staging 补丁目录存在"
fi
log "  configure:            $(wc -l < configure) 行"
log "  config.h.in:          $(wc -l < include/config.h.in) 行"
log "  dlls 数量:            $(ls dlls | wc -l)"
log "  VERSION:              $(cat VERSION)"
log "源码准备完成: $(pwd)"
