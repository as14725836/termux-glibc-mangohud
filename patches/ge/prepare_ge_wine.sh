apply_one() {
  local p="$1"
  local rel="$2"
  [ -f "$p" ] || { log "    缺失: $rel"; PATCH_FAILED=$((PATCH_FAILED + 1)); return 0; }
  PATCH_TOTAL=$((PATCH_TOTAL + 1))
  if ! patch -Np1 --batch --forward --no-backup-if-mismatch <"$p" >/dev/null 2>&1; then
    PATCH_FAILED=$((PATCH_FAILED + 1))
    log "    WARN: $rel 打不上（继续）"
  fi
}

apply_dir() {
  local d="$1"
  local label="$2"
  if [ ! -d "$d" ]; then
    log "  [$label] 目录不存在，跳过"
    return 0
  fi
  local before=$PATCH_FAILED n=0
  for p in "$d"/*.patch; do
    [ -f "$p" ] || continue
    n=$((n + 1))
    apply_one "$p" "$label/$(basename "$p")"
  done
  log "  [$label] $n 份，失败 $((PATCH_FAILED - before))"
}

