#!/usr/bin/env bash
# ==============================================================
# 按 GE-Proton（gloriouseggroll/proton-ge-custom）的 patch 流程准备 Wine 源码树
# ==============================================================
# 目标：复刻 GE 的 wine 源码准备过程，不改动调用方的 configure/make/打包流程。
#
# GE 的 wine 不是某个现成仓库分支，而是三步拼出来的：
#   1. ValveSoftware/wine @ <GE .gitmodules 里 pin 的 sha>
#   2. wine-staging     @ <GE .gitmodules 里 pin 的 sha>，用 patchinstall.py 打
